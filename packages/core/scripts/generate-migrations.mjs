import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const databases = ["thread", "scope-config", "knowledge", "memory"];
const packageRoot = resolve(import.meta.dirname, "..");

const decodeJournal = (value, database) => {
  if (
    typeof value !== "object" ||
    value === null ||
    typeof value.version !== "string" ||
    value.dialect !== "sqlite" ||
    !Array.isArray(value.entries)
  )
    throw new Error(`Invalid migration journal for ${database}.`);
  const entries = value.entries.map((entry) => {
    if (
      typeof entry !== "object" ||
      entry === null ||
      typeof entry.idx !== "number" ||
      typeof entry.version !== "string" ||
      typeof entry.when !== "number" ||
      typeof entry.tag !== "string" ||
      typeof entry.breakpoints !== "boolean"
    )
      throw new Error(`Invalid migration journal entry for ${database}.`);
    return {
      idx: entry.idx,
      version: entry.version,
      when: entry.when,
      tag: entry.tag,
      breakpoints: entry.breakpoints,
    };
  });
  return { version: value.version, dialect: value.dialect, entries };
};

for (const database of databases) {
  const result = spawnSync("pnpm", ["exec", "drizzle-kit", "generate", "--config", "drizzle.config.ts"], {
    cwd: packageRoot,
    env: { ...process.env, KARMI_DATABASE: database },
    stdio: "inherit",
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

for (const database of databases) {
  const directory = resolve(packageRoot, "src", "db", database, "migrations");
  const journal = decodeJournal(
    JSON.parse(readFileSync(resolve(directory, "meta", "_journal.json"), "utf8")),
    database,
  );
  const migrations = Object.fromEntries(
    journal.entries.map((entry) => {
      const filename = readdirSync(directory).find(
        (candidate) => candidate.startsWith(`${String(entry.idx).padStart(4, "0")}_`) && candidate.endsWith(".sql"),
      );
      if (!filename) throw new Error(`Missing migration SQL for ${database}/${entry.tag}.`);
      return [`m${String(entry.idx).padStart(4, "0")}`, readFileSync(resolve(directory, filename), "utf8")];
    }),
  );
  const source = `// This file is generated by pnpm db:generate.\nexport default ${JSON.stringify({ journal, migrations }, null, 2)};\n`;
  writeFileSync(resolve(directory, "index.ts"), source);
}
